# Alien colors
alien_color = ['green', 'yellow', 'red']
# Else-if chain for alien colors
for color in alien_color:
    if color == 'green':
        print("Alien color is green. You just earned 5 points!")
    elif color == 'yellow':
        print("Alien color is yellow. You just earned 10 points!")
    elif color == 'red':
        print("Alien color is red. You just earned 15 points!")

