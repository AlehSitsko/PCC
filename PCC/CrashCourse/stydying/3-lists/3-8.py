# List of places to see
places = ["Rome", "Paris", "London", "Athens", "Berlin"]
# Print the list of places
print(places)
# Sorted list of places
places_sorted = sorted(places)
# Print the sorted list of places
print(places_sorted)
# Sorted-reverse list of places
places_sorted_reverse = sorted(places, reverse=True)
# Print the sorted-reverse list of places
print(places_sorted_reverse)
# Places back-reversed
places_sorted_reverse.reverse
print(places)
# Alphabethical order
places.sort()
print(places)
